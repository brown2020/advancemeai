"use client";

import dynamic from "next/dynamic";
import { Compass } from "lucide-react";
import {
  PageContainer,
  PageHeader,
  LoadingState,
  ErrorDisplay,
  CardGrid,
  EmptyState,
  SectionHeading,
} from "@/components/common/UIComponents";
import { Button } from "@/components/ui/button";
import { SectionCard } from "@/components/practice/SectionCard";
import { SignInGate } from "@/components/auth/SignInGate";
import { SignInGateIcons } from "@/components/auth/sign-in-gate-icons";
import type { TestSection } from "@/services/practiceTestService";

const PracticeDebug = dynamic(() => import("./PracticeDebug"), { ssr: false });

const HUB_DESCRIPTION =
  "Every question is generated by AI and tuned to your skill level. Start with a full-length test, or sharpen one section at a time.";

export function HubHeader() {
  return (
    <PageHeader
      eyebrow="SAT Prep"
      title="Practice that adapts to you"
      description={HUB_DESCRIPTION}
    />
  );
}

export function DebugPanel({
  showDebug,
  onToggle,
}: {
  showDebug: boolean;
  onToggle: () => void;
}) {
  return (
    <div className="mb-6">
      <div className="text-right">
        <Button
          type="button"
          variant="ghost"
          size="sm"
          onClick={onToggle}
          aria-pressed={showDebug}
        >
          {showDebug ? "Hide debug info" : "Show debug info"}
        </Button>
      </div>
      {showDebug && <PracticeDebug />}
    </div>
  );
}

export function PracticeDebugSlot({
  enabled,
  showDebug,
  onToggle,
}: {
  enabled: boolean;
  showDebug: boolean;
  onToggle: () => void;
}) {
  if (!enabled) return null;
  return <DebugPanel showDebug={showDebug} onToggle={onToggle} />;
}

export function PracticeLoading({ authIsGuaranteed }: { authIsGuaranteed: boolean }) {
  return (
    <PageContainer>
      <HubHeader />
      <LoadingState message={practiceLoadingMessage(authIsGuaranteed)} />
    </PageContainer>
  );
}

function practiceLoadingMessage(authIsGuaranteed: boolean): string {
  if (authIsGuaranteed) return "Loading SAT Prep...";
  return "Checking your session...";
}

export function PracticeSignIn({
  authIsGuaranteed,
  debugSlot,
}: {
  authIsGuaranteed: boolean;
  debugSlot: React.ReactNode;
}) {
  return (
    <PageContainer>
      <HubHeader />
      {debugSlot}
      <SignInGate
        title="Sign in to start SAT Prep"
        description={signInGateDescription(authIsGuaranteed)}
        icon={SignInGateIcons.practice}
      />
    </PageContainer>
  );
}

function signInGateDescription(authIsGuaranteed: boolean): string {
  if (authIsGuaranteed) {
    return "Your session expired. Sign in again to access practice tests.";
  }
  return "Our AI-powered practice tests are personalized to your skill level and help you improve gradually.";
}

export function PracticeSectionList({
  error,
  loading,
  sections,
}: {
  error: string | null;
  loading: boolean;
  sections: TestSection[];
}) {
  if (error) return <ErrorDisplay message={error} />;
  if (loading) return <LoadingState message="Loading sections..." />;
  if (sections.length === 0) return <PracticeSectionsEmpty />;
  return <PracticeSectionGrid sections={sections} />;
}

function PracticeSectionsEmpty() {
  return (
    <EmptyState
      icon={<Compass />}
      title="No sections yet"
      message="Practice sections aren't available right now. Please check back soon."
    />
  );
}

function PracticeSectionGrid({ sections }: { sections: TestSection[] }) {
  return (
    <CardGrid columns={{ default: 1, md: 2, lg: 4 }}>
      {sections.map((section) => (
        <SectionCard key={section.id} section={section} />
      ))}
    </CardGrid>
  );
}

export function PracticeSectionHeading() {
  return <SectionHeading title="Practice by section" icon={<Compass />} />;
}
